import SwiftUI

struct GalaxyStar {
    
    let x: CGFloat
    let y: CGFloat
    
    /// Visual diameter.
    let size: CGFloat
    
    /// Base opacity.
    let opacity: Double
    
    /// Progress at which this star appears
    /// during a growth/completion animation.
    let revealAt: Double
    
}
